export type IconSpec = string | [string, string];

/** font awesome icon, accepts 'trash' or ['fab', 'github'] */
export function Icon({ icon, ...props }: Omit<FontAwesomeIconProps, 'icon'> & { icon: IconSpec }) {
  const spec: [IconPrefix, IconName] = Array.isArray(icon)
    ? [icon[0] as IconPrefix, icon[1] as IconName]
    : ['fas', icon as IconName];
  return <FontAwesomeIcon icon={spec} fixedWidth {...props} />;
}

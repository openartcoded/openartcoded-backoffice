import { Fragment } from 'react';
import { ActionIcon, Table } from '@mantine/core';
import { useQuery } from '@tanstack/react-query';
import { Icon } from '@/components/Icon';
import { PageHeader } from '@/components/ui';
import { cvApi } from '@/api/misc';
import { fmtDateTime } from '@/lib/format';
import { confirm } from '@/lib/ui';

export function CvRequestsPage() {
  const { data: requests, refetch } = useQuery({ queryKey: ['cv-requests'], queryFn: cvApi.downloadRequests });

  return (
    <>
      <PageHeader title="CV download requests" back={{ to: '/cv', label: 'Curriculum' }} />
      <Table>
        <Table.Thead>
          <Table.Tr>
            <Table.Th>Email</Table.Th>
            <Table.Th>Phone number</Table.Th>
            <Table.Th>Daily rate</Table.Th>
            <Table.Th>Availability</Table.Th>
            <Table.Th>Date received</Table.Th>
            <Table.Th w={60} />
          </Table.Tr>
        </Table.Thead>
        <Table.Tbody>
          {requests?.map((r) => (
            <Fragment key={r.id}>
              <Table.Tr>
                <Table.Td>{r.email}</Table.Td>
                <Table.Td>{r.phoneNumber}</Table.Td>
                <Table.Td>{String(r.dailyRate ?? '')}</Table.Td>
                <Table.Td>{String(r.availability ?? '')}</Table.Td>
                <Table.Td>{fmtDateTime(r.dateReceived)}</Table.Td>
                <Table.Td>
                  <ActionIcon
                    variant="subtle"
                    color="red"
                    aria-label="delete"
                    onClick={async () => {
                      if (await confirm(`Delete the request of ${r.email ?? ''}?`)) {
                        await cvApi.deleteDownloadRequest(r.id!);
                        refetch();
                      }
                    }}
                  >
                    <Icon icon="trash" />
                  </ActionIcon>
                </Table.Td>
              </Table.Tr>
              {!!r.htmlContent?.length && (
                <Table.Tr>
                  {/* html generated by the backend from the request */}
                  <Table.Td colSpan={6} dangerouslySetInnerHTML={{ __html: r.htmlContent }} />
                </Table.Tr>
              )}
            </Fragment>
          ))}
        </Table.Tbody>
      </Table>
    </>
  );
}
